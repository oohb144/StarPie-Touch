	public static string GetInitials(string text)
	{
		if (string.IsNullOrEmpty(text))
		{
			return "";
		}
		StringBuilder stringBuilder = new StringBuilder();
		foreach (char c in text)
		{
			if ((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9'))
			{
				stringBuilder.Append(c);
			}
			else if (c >= 'A' && c <= 'Z')
			{
				stringBuilder.Append(char.ToLowerInvariant(c));
			}
			else if (c >= '一' && c <= '龥')
			{
				char c2 = ConvertCharToInitial(c);
				if (c2 != 0)
				{
					stringBuilder.Append(c2);
				}
			}
		}
		return stringBuilder.ToString();
	}

	public static string GetFullPinyin(string text)
	{
		if (string.IsNullOrEmpty(text))
		{
			return "";
		}
		StringBuilder stringBuilder = new StringBuilder();
		foreach (char c in text)
		{
			if ((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9'))
			{
				stringBuilder.Append(c);
			}
			else if (c >= 'A' && c <= 'Z')
			{
				stringBuilder.Append(char.ToLowerInvariant(c));
			}
			else if (c >= '一' && c <= '龥')
			{
				string text2 = ConvertCharToPinyin(c);
				if (!string.IsNullOrEmpty(text2))
				{
					stringBuilder.Append(text2.ToLowerInvariant());
				}
			}
		}
		return stringBuilder.ToString();
	}

	private static char ConvertCharToInitial(char c)
	{
		string text = ConvertCharToPinyin(c);
		if (!string.IsNullOrEmpty(text))
		{
			return char.ToLowerInvariant(text[0]);
		}
		return '\0';
	}

